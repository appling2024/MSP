"""**Biterm LDA** - разновидность тематического моделирования, специально разработанная для коротких текстов (таких как твиты, заголовки новостей, сообщения в мессенджерах и т.д.).

Как работает алгоритм:
- Собираются все битермы из всего корпуса.
- Модель пытается определить, какие темы объясняют со-встречаемость слов.
- Для каждой темы строится распределение слов (как в обычной LDA).
- Получается более устойчивое моделирование, особенно при малом контексте.




"""

