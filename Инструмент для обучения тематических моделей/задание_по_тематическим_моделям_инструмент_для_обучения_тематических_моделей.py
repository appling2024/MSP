def preprocess_ru(text):
    # Удаляем специальные символы и цифры
    text = re.sub(r'[^а-яА-ЯёЁ\s]', '', text.lower())
    text = re.sub(r'\d+', '', text)

    # Токенизация по пробелам
    tokens = text.split()

    # Лемматизация и фильтрация
    lemmas = []
    for token in tokens:
        if len(token) > 2 and token not in russian_stopwords:
            try:
                parsed = morph.parse(token)[0]
                lemma = parsed.normal_form
                lemmas.append(lemma)
            except Exception:
                # В случае ошибки просто пропускаем слово
                continue
    return lemmas

