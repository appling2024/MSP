import os

# Путь к подпапке с .txt-файлами (уточни свой путь)
folder_path = "/content/rukopis_extracted/Rukopis"

texts = []

for root, dirs, files in os.walk(folder_path):
    for filename in files:
        if filename.endswith('.txt'):
            try:
                with open(os.path.join(root, filename), 'r', encoding='windows-1251', errors='ignore') as f:
                    texts.append(f.read())
            except Exception as e:
                print(f"Ошибка с файлом {filename}: {e}")

print(f"✅ Загружено текстов: {len(texts)}")

import nltk
import spacy
from nltk.corpus import stopwords
from gensim.utils import simple_preprocess
from gensim.models.phrases import Phrases, Phraser
from pymorphy3 import MorphAnalyzer

nltk.download('stopwords')
stop_words = set(stopwords.words("russian"))
morph = MorphAnalyzer()
nlp = spacy.load("ru_core_news_sm")

def preprocess(text):
    tokens = simple_preprocess(text, deacc=True)
    tokens = [w for w in tokens if w not in stop_words and len(w) > 2]
    lemmas = [morph.parse(token)[0].normal_form for token in tokens]
    return lemmas
#simple_preprocess(text, deacc=True) — разбивает текст на токены, приводит к нижнему регистру, удаляет пунктуацию.
#Удаляем из токенов стоп-слова и очень короткие слова (меньше 3 символов).
#Применяем морфологический разбор и лемматизацию через pymorphy3 — получаем норм форму каждого слова.
#Возвращаем список лемм (лемматизированных слов) для текстов.

processed_texts = [preprocess(text) for text in texts]

# биграммы и триграммы (фразовые выражения)
bigram = Phrases(processed_texts, min_count=5, threshold=100)
bigram_mod = Phraser(bigram)
trigram = Phrases(bigram_mod[processed_texts], threshold=100)
trigram_mod = Phraser(trigram)

#Phrases находит частые сочетания слов (например, «новый_год»), которые лучше рассматривать как единый токен.
#min_count=5 — биграмма должна встречаться минимум 5 раз, чтобы мы её признали устойчивым выражением.
#threshold=100 — порог для определения, насколько сильно слова должны быть связаны, чтобы объединиться в биграмму/триграмму.
#Phraser — оптимизированная версия для быстрого применения найденных фраз к текстам.
#Последняя строчка — применяем биграммы и триграммы к исходному корпусу, получаем тексты с фразовыми выражениями, которые будут учтены как единые токены.

texts_ngram = [trigram_mod[bigram_mod[text]] for text in processed_texts]

"""**Gensim LDA + оценка**"""

from gensim.corpora.dictionary import Dictionary
from gensim.models import LdaModel, CoherenceModel

#создание словаря (Dictionary) и корпуса (Corpus):
#filter_extremes:
#no_below=5: удаляет слова, которые встречаются в менее чем 5 документах.
#no_above=0.5: удаляет слова, которые встречаются более чем в 50% документов.
#doc2bow(text) — преобразует каждый документ в список пар (token_id, частота) → формат Bag-of-Words.

id2word = Dictionary(texts_ngram) #Dictionary слово + уникальный ID
id2word.filter_extremes(no_below=5, no_above=0.5)
corpus = [id2word.doc2bow(text) for text in texts_ngram]

#Обучение LDA-модели - вероятностная тематическая модель, которая автоматически выделяет скрытые темы в текстах.
lda_model = LdaModel(
    corpus=corpus,
    id2word=id2word,
    num_topics=10,
    random_state=100,
    passes=10, #сколько раз модель проходит по корпусу (повышает качество).
    alpha='auto' #автоматическая настройка распределения тем по документам.
)

print("🧠 Топики:")
for idx, topic in lda_model.print_topics(-1): #weight - вероятность (или вклад) слова в этой теме. Это вероятность того, что это слово будет выбрано, если случайным образом выбрать слово из темы.
    print(f"{idx}: {topic}")

coherence_model = CoherenceModel(model=lda_model, texts=texts_ngram, dictionary=id2word, coherence='c_v')
print(f"📊 Coherence Score: {coherence_model.get_coherence():.4f}")

"""**CoherenceModel** — вычисляет коэффициент согласованности (coherence), отражающий интерпретируемость тем.

**c_v** — метрика, основанная на совместной встречаемости слов в теме.

**0.2718** — это низковатое значение

**Визуализация LDA**
"""

