    soup = BeautifulSoup(content, 'html.parser')
    # Находим все теги <w> — это отдельные слова в тексте
    w_tags = soup.find_all('w')
    # Создаём список для хранения контекстов
    contexts = []

    # Проходим по каждому слову (тегу <w>) с индексом i
