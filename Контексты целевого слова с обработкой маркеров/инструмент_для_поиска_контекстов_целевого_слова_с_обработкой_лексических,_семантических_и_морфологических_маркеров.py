"""**Функция предобработки preprocess** - на вход получает контекст в сыром виде (то есть со всеми тегами и ненужными скобочками) и преобразует его так, чтобы по нему было удобно искать."""

import re
def preprocess(context):
  info = {'lex': [], 'sem': [], 'tokens': [], 'sentence': ''} # словарь вида {lex: список лемм, sem: список семантических тегов, tokens: список словоформ, sentence: контекст в виде удобочитаемой строки}
  pattern = r'<w>.+?</w>' # с помощью ? мы можем сделать наше регулярное выражение нежадным!!
  words = re.findall(pattern, context) # добыли "слова", но тоже пока что в некрасивом виде

  tokens = []
  for word in words:
    lex_pattern = r'lex=\'.+?\''
    lex_raw = re.search(lex_pattern, word)
    if lex_raw:
      lex = lex_raw.group().split('=')[1].strip("'")  # нашли лексему
      info['lex'].append(lex) # добавили лексему в наш словарь


    sem_pattern = r'sem=\'.+?\''
    sem_raw = re.search(sem_pattern, word)
    if sem_raw:  # проверяем, что совпадение найдено (не у всех слов есть семантика)
      sem = sem_raw.group().split('=')[1].strip("'").split()  # нашли семантику, причём в список добавляем семантический тег не единой строкой, а списком, чтобы иметь возможность искать по отдельным тегам, а не по всему в куче
      info["sem"].append(sem) # добавили семантические теги в наш словарь

    form_pattern = '>\w+<'
    form_raw = re.search(form_pattern, word)
    if form_raw:
      form = form_raw.group().strip('<>')  # нашли словоформу
      info['tokens'].append(form) # добавили словоформу в наш словарь
      tokens.append(form) # добавили найденную словоформу в список всех словоформ данного предложения

  # Соберём все слова в одно предложение-контекст
  sentence = ' '.join(tokens)
  info['sentence'] = sentence # добавили полученное предложение в наш словарь

  return info # возвращаем словарь с полной информации о данном контексте

